#!/bin/bash
#
# Submitter for the Rosetta/GenKIC LP -> CP search arm. Calls sbatch and nothing else: no
# work of its own, so the pipeline is reproducible from the printed commands alone.
#
#   ./scripts/submit_genkic.sh --smoke                 one real complex, end to end (do this first)
#   ./scripts/submit_genkic.sh --search                the substantive search array
#   ./scripts/submit_genkic.sh --sdedit                grade existing SDEdit outputs, same contract
#   ./scripts/submit_genkic.sh --confirm               re-score winners with many more repeats
#   ./scripts/submit_genkic.sh --report                aggregate + report over an existing run
#   ./scripts/submit_genkic.sh --all                   search + sdedit as siblings, then report
#
# --all submits the search array and the SDEdit grading as SIBLINGS, not in sequence: the
# SDEdit arm reads structures that already exist, so making it wait on the search would only
# lengthen the critical path. The report waits on both with afterany.
#
#   ./scripts/submit_genkic.sh --search RUN_ID=genkic_20260928_2100    RESUME an existing run
#   ./scripts/submit_genkic.sh --search ATTEMPTS_PER_CALL=20000 CALLS=8 TIME_BUDGET_S=25200
#   ./scripts/submit_genkic.sh --search EXAMPLES="LNR_2qos_C_A LNR_1bjr_E_I"
#
# Any VAR=value argument overrides a preamble default. They are written into a timestamped
# env file whose PATH is passed to each job as a positional argument -- never via
# `sbatch --export`, which sets SLURM_GET_USER_ENV=1, makes slurmd fail to rebuild the login
# environment, and leaves the job requeued and HELD with every dependent stranded on
# Dependency (measured here, jobs 22184 and 22243).
#
# To RESUME: resubmit the identical command with the same RUN_ID. Each shard skips the
# row_keys already in its own output file, so nothing is recomputed.

set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO"
mkdir -p slurm_logs evaluation_results/_env

MODE=""
OVERRIDES=()
for arg in "$@"; do
  case "$arg" in
    --smoke|--search|--sdedit|--confirm|--report|--all)
      [[ -n "$MODE" ]] && { echo "FATAL: pick one mode, got $MODE and $arg" >&2; exit 1; }
      MODE="$arg" ;;
    *=*) OVERRIDES+=("$arg") ;;
    *) echo "FATAL: unrecognized argument: $arg" >&2; exit 1 ;;
  esac
done
[[ -n "$MODE" ]] || { echo "FATAL: pick a mode (--smoke | --search | --report | --all)" >&2; exit 1; }

# One env file per submission. A file (not a comma-joined export list) also means
# list-valued variables need no encoding -- CHEMISTRIES and BUDGETS contain spaces.
STAMP="$(date +%Y%m%d_%H%M%S)"
ENV_FILE="${REPO}/evaluation_results/_env/genkic_${STAMP}.env"
{
  echo "# generated by submit_genkic.sh at ${STAMP}"
  echo "REPO=${REPO}"
  # RUN_ID is fixed HERE rather than left to each job's own $(date), or the array's tasks
  # would each invent a different one and scatter their rows across N directories.
  # Checked per override, not against "${OVERRIDES[*]}": that joins them into ONE line, so an
  # anchored ^RUN_ID= only matches when RUN_ID happens to be the FIRST override, and otherwise
  # the default is written too. Sourcing lets the later line win, so it worked by accident --
  # but the file then held two RUN_IDs and the submitter printed the wrong one.
  _have_run_id=0
  for o in "${OVERRIDES[@]+"${OVERRIDES[@]}"}"; do
    [[ "$o" == RUN_ID=* ]] && _have_run_id=1
  done
  (( _have_run_id )) || echo "RUN_ID='genkic_${STAMP}'"
  # Values MUST be single-quoted. The env file is SOURCED, so a list-valued override written
  # verbatim -- BUDGETS=0 1 2 -- parses as `BUDGETS=0` followed by running `1` with argument
  # `2`, and the job dies with "1: command not found". Measured: it killed all 20 search shards
  # on first launch. Embedded single quotes are escaped the POSIX way ('\'').
  for o in "${OVERRIDES[@]+"${OVERRIDES[@]}"}"; do
    printf "%s='%s'\n" "${o%%=*}" "$(printf '%s' "${o#*=}" | sed "s/'/'\\\\''/g")"
  done
} > "$ENV_FILE"

# Values in the env file are single-quoted (see above), so strip the quotes when reading one
# back here. Left in, RUN_ID would become "'genkic_x'" and the submitter would print and
# suggest a resume command with a run id that does not match the one the jobs use.
# LAST match, not the first: the file is sourced top to bottom, so if a key appears more than
# once the last line is the value the jobs actually see.
env_get() { sed -n "s/^$1=//p" "$ENV_FILE" | tail -1 | sed "s/^'//; s/'$//"; }
RUN_ID="$(env_get RUN_ID)"
echo "env file : $ENV_FILE"
echo "run id   : $RUN_ID"
sed 's/^/           /' "$ENV_FILE"
echo

# Scrub SLURM_* so that submitting from inside an allocation does not leak this shell's job
# context (SLURM_JOB_ID, SLURM_MEM_PER_NODE, ...) into the new jobs' environments, where it
# would override their own #SBATCH requests.
run_sbatch() {
  env $(env | grep -o '^SLURM_[A-Z_]*' | sed 's/^/-u /' | tr '\n' ' ') sbatch "$@"
}

SEARCH_SHARDS="$(env_get SEARCH_SHARDS)"
SEARCH_SHARDS="${SEARCH_SHARDS:-12}"

SDEDIT_SHARDS="$(env_get SDEDIT_SHARDS)"
SDEDIT_SHARDS="${SDEDIT_SHARDS:-12}"

CONFIRM_SHARDS="$(env_get CONFIRM_SHARDS)"
CONFIRM_SHARDS="${CONFIRM_SHARDS:-4}"

SMOKE_ID=""
SEARCH_ID=""
SDEDIT_ID=""
CONFIRM_ID=""

submit_smoke() {
  local cmd=(sbatch scripts/genkic_smoke.sbatch "$ENV_FILE")
  echo "+ ${cmd[*]}"
  SMOKE_ID="$(run_sbatch "${cmd[@]:1}" | awk '{print $NF}')"
  echo "  submitted smoke as job $SMOKE_ID"
}

submit_search() {
  local dep=()
  [[ -n "$SMOKE_ID" ]] && dep=(--dependency=afterok:"$SMOKE_ID")
  local cmd=(sbatch "${dep[@]}" --array=0-$((SEARCH_SHARDS - 1))
             scripts/genkic_search.sbatch "$ENV_FILE")
  echo "+ ${cmd[*]}"
  SEARCH_ID="$(run_sbatch "${cmd[@]:1}" | awk '{print $NF}')"
  echo "  submitted search array (${SEARCH_SHARDS} shards) as job $SEARCH_ID"
}

submit_sdedit() {
  local cmd=(sbatch --array=0-$((SDEDIT_SHARDS - 1))
             scripts/genkic_sdedit.sbatch "$ENV_FILE")
  echo "+ ${cmd[*]}"
  SDEDIT_ID="$(run_sbatch "${cmd[@]:1}" | awk '{print $NF}')"
  echo "  submitted sdedit grading (${SDEDIT_SHARDS} shards) as job $SDEDIT_ID"
}

submit_confirm() {
  local dep=() waits=()
  [[ -n "$SEARCH_ID" ]] && waits+=("$SEARCH_ID")
  [[ -n "$SDEDIT_ID" ]] && waits+=("$SDEDIT_ID")
  if [[ ${#waits[@]} -gt 0 ]]; then
    dep=(--dependency=afterany:"$(IFS=:; echo "${waits[*]}")")
  fi
  local cmd=(sbatch "${dep[@]}" --array=0-$((CONFIRM_SHARDS - 1))
             scripts/genkic_confirm.sbatch "$ENV_FILE")
  echo "+ ${cmd[*]}"
  CONFIRM_ID="$(run_sbatch "${cmd[@]:1}" | awk '{print $NF}')"
  echo "  submitted confirm (${CONFIRM_SHARDS} shards) as job $CONFIRM_ID"
}

submit_report() {
  local dep=() waits=()
  # afterany, not afterok: a shard that hit its walltime still produced rows worth
  # aggregating, and the report's own gate reports partial coverage explicitly.
  [[ -n "$SEARCH_ID" ]] && waits+=("$SEARCH_ID")
  [[ -n "$SDEDIT_ID" ]] && waits+=("$SDEDIT_ID")
  [[ -n "$CONFIRM_ID" ]] && waits+=("$CONFIRM_ID")
  if [[ ${#waits[@]} -gt 0 ]]; then
    dep=(--dependency=afterany:"$(IFS=:; echo "${waits[*]}")")
  fi
  local cmd=(sbatch "${dep[@]}" scripts/genkic_report.sbatch "$ENV_FILE")
  echo "+ ${cmd[*]}"
  local id
  id="$(run_sbatch "${cmd[@]:1}" | awk '{print $NF}')"
  echo "  submitted report as job $id"
}

case "$MODE" in
  --smoke)  submit_smoke ;;
  --search) submit_search ;;
  --sdedit) submit_sdedit ;;
  --confirm) submit_confirm ;;
  --report) submit_report ;;
  # No smoke in --all: the smoke is a preflight you run once and read, not a gate to put in
  # front of every launch. Run it first, look at it, then launch this.
  --all)    submit_search; submit_sdedit; submit_confirm; submit_report ;;
esac

echo
echo "watch:   squeue -u $USER"
echo "logs:    tail -f ${REPO}/slurm_logs/genkic_*_*.out"
echo "resume:  $0 $MODE RUN_ID=$RUN_ID"
