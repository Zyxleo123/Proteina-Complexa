#!/bin/bash
# Submitter for the provenance-paired LP -> CP dataset. Calls sbatch and nothing else.
#
#   bash scripts/submit_lp2cp_pairs.sh --submit <stage> [options]
#
# Stages:
#   verify    CPU         unit + integration tests (geometry, no network, no AFDB)
#   parents   CPU         decode CPSea provenance -> parents.tsv + pairs_todo.parquet
#   fetch     CPU array   download the AFDB parent models (resumable)
#   pair      CPU array   slice, align and write the LP side of every pair (resumable)
#   report    CPU         diagnose the built set and render the report
#   all       verify -> parents -> fetch -> pair -> report
#
# Everything is CPU: nothing here needs a GPU, and asking for one would only queue this
# behind real training work.
#
# Writes ONE timestamped env file per submission and passes its PATH as a positional
# argument. Never `sbatch --export`: any explicit export list (--export=ALL,K=v and
# --export=NONE alike) sets SLURM_GET_USER_ENV=1, slurmd then fails to rebuild the login
# environment on the compute node, and the job is requeued and HELD, stranding every
# dependent on Dependency.
#
# The shard counts are written into the env file by THIS script, so the array size and the
# value the job shards by can never disagree. Do not change them mid-build: re-sharding
# reassigns every example and duplicates pairs into different shards.
#
#   bash scripts/submit_lp2cp_pairs.sh --submit all --smoke      # 200 parents, own root
#   bash scripts/submit_lp2cp_pairs.sh --submit all              # 20,000 parents

set -euo pipefail
REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO"

STAGE=""; DRYRUN=0; SMOKE=0
CPU_PARTITION="cpu"
VERIFY_TIME="00:30:00"
PARENTS_TIME="02:00:00"
FETCH_TIME="04:00:00"
PAIR_TIME="08:00:00"
REPORT_TIME="04:00:00"
FETCH_SHARDS=""; PAIR_SHARDS=""
declare -a EXTRA_ENV=()

usage() { sed -n '2,28p' "$0"; exit "${1:-0}"; }

while [[ $# -gt 0 ]]; do
  case "$1" in
    --submit)         STAGE="$2";          shift 2 ;;
    --cpu-partition)  CPU_PARTITION="$2";  shift 2 ;;
    --verify-time)    VERIFY_TIME="$2";    shift 2 ;;
    --parents-time)   PARENTS_TIME="$2";   shift 2 ;;
    --fetch-time)     FETCH_TIME="$2";     shift 2 ;;
    --pair-time)      PAIR_TIME="$2";      shift 2 ;;
    --report-time)    REPORT_TIME="$2";    shift 2 ;;
    --fetch-shards)   FETCH_SHARDS="$2";   shift 2 ;;
    --pair-shards)    PAIR_SHARDS="$2";    shift 2 ;;
    # Anything VAR=value goes into the env file, so every knob in
    # scripts/_lp2cp_pair_preamble.sh is settable without editing a script.
    --set)            EXTRA_ENV+=("$2");   shift 2 ;;
    --smoke)          SMOKE=1;             shift ;;
    --dry-run)        DRYRUN=1;            shift ;;
    -h|--help)        usage 0 ;;
    *) echo "unknown arg: $1" >&2; usage 1 >&2 ;;
  esac
done
[[ -n "$STAGE" ]] || { echo "FATAL: --submit <stage> is required" >&2; usage 1 >&2; }

case "$STAGE" in
  verify|parents|fetch|pair|report|all) ;;
  *) echo "FATAL: unknown stage '$STAGE'" >&2; usage 1 >&2 ;;
esac

# Defaults mirror the preamble's, including the smoke reduction, because the array size is
# decided here and the job must shard by the same number.
if [[ -z "$FETCH_SHARDS" ]]; then [[ $SMOKE -eq 1 ]] && FETCH_SHARDS=2 || FETCH_SHARDS=8; fi
if [[ -z "$PAIR_SHARDS"  ]]; then [[ $SMOKE -eq 1 ]] && PAIR_SHARDS=2  || PAIR_SHARDS=8;  fi

STAMP="$(date +%Y%m%d_%H%M%S)"
ENV_DIR="${REPO}/env_files"; mkdir -p "$ENV_DIR" slurm_logs
ENV_FILE="${ENV_DIR}/lp2cp_pairs_${STAMP}.env"
{
  echo "# generated by submit_lp2cp_pairs.sh at ${STAMP}"
  echo "REPO=${REPO}"
  echo "SMOKE=${SMOKE}"
  echo "FETCH_SHARDS=${FETCH_SHARDS}"
  echo "PAIR_SHARDS=${PAIR_SHARDS}"
  for kv in "${EXTRA_ENV[@]+"${EXTRA_ENV[@]}"}"; do echo "$kv"; done
} > "$ENV_FILE"
echo "env file: $ENV_FILE"
sed 's/^/  /' "$ENV_FILE"

# Submitting from inside an allocation would otherwise leak this job's SLURM_* into the
# child, which confuses the array logic and the resume checks.
for v in $(compgen -v | grep '^SLURM_' || true); do unset "$v" || true; done

submit() {  # submit <description> <sbatch args...>
  local desc="$1"; shift
  if [[ $DRYRUN -eq 1 ]]; then
    # To stderr: stdout is the job id this function returns to its caller.
    { printf 'DRY-RUN %-10s sbatch' "$desc"; printf ' %q' "$@"; printf '\n'; } >&2
    echo "999999"
    return
  fi
  local out; out="$(sbatch "$@")"
  echo "$desc: $out" >&2
  awk '{print $NF}' <<<"$out"
}

VERIFY_JID=""; PARENTS_JID=""; FETCH_JID=""; PAIR_JID=""

if [[ "$STAGE" == "verify" || "$STAGE" == "all" ]]; then
  VERIFY_JID="$(submit verify \
    --partition="$CPU_PARTITION" --time="$VERIFY_TIME" \
    scripts/lp2cp_pair_verify.sbatch "$ENV_FILE")"
fi

if [[ "$STAGE" == "parents" || "$STAGE" == "all" ]]; then
  DEP=(); [[ -n "$VERIFY_JID" ]] && DEP=(--dependency=afterok:"$VERIFY_JID")
  PARENTS_JID="$(submit parents \
    --partition="$CPU_PARTITION" --time="$PARENTS_TIME" \
    "${DEP[@]}" \
    scripts/lp2cp_pair_parents.sbatch "$ENV_FILE")"
fi

if [[ "$STAGE" == "fetch" || "$STAGE" == "all" ]]; then
  DEP=(); [[ -n "$PARENTS_JID" ]] && DEP=(--dependency=afterok:"$PARENTS_JID")
  FETCH_JID="$(submit fetch \
    --partition="$CPU_PARTITION" --time="$FETCH_TIME" \
    --array=0-$((FETCH_SHARDS - 1)) \
    "${DEP[@]}" \
    scripts/lp2cp_pair_fetch.sbatch "$ENV_FILE")"
fi

if [[ "$STAGE" == "pair" || "$STAGE" == "all" ]]; then
  DEP=(); [[ -n "$FETCH_JID" ]] && DEP=(--dependency=afterok:"$FETCH_JID")
  PAIR_JID="$(submit pair \
    --partition="$CPU_PARTITION" --time="$PAIR_TIME" \
    --array=0-$((PAIR_SHARDS - 1)) \
    "${DEP[@]}" \
    scripts/lp2cp_pair_build.sbatch "$ENV_FILE")"
fi

if [[ "$STAGE" == "report" || "$STAGE" == "all" ]]; then
  DEP=(); [[ -n "$PAIR_JID" ]] && DEP=(--dependency=afterok:"$PAIR_JID")
  submit report \
    --partition="$CPU_PARTITION" --time="$REPORT_TIME" \
    "${DEP[@]}" \
    scripts/lp2cp_pair_report.sbatch "$ENV_FILE" >/dev/null
fi

echo "submitted stage: $STAGE  (fetch shards ${FETCH_SHARDS}, pair shards ${PAIR_SHARDS})"
