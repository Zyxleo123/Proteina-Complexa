#!/bin/bash
# Submitter for the FlowEdit LP->CP chain. Calls sbatch and nothing else.
#
#   bash scripts/submit_flowedit.sh --submit <stage> [options]
#
# Stages:
#   smoke      GPU   one real end-to-end run: a few peptides, both arms, full scoring
#   gen        GPU   sharded candidate generation for ONE arm (--method)
#   paired     GPU   both arms as siblings, same settings, same output dir
#   rosetta    CPU   paired interface-dG on the shortlist, with repeats
#   report     CPU   aggregate + the results document
#
# GPU work and CPU work are separate jobs on separate partitions: asking for a GPU to
# aggregate JSONL rows just queues the aggregation behind real work.
#
# Configuration travels as ONE timestamped env file passed as a POSITIONAL argument.
# `sbatch --export` is never used -- any explicit export list sets SLURM_GET_USER_ENV=1,
# slurmd then fails to rebuild the login environment on the compute node, and the job is
# requeued and HELD, stranding every dependent on Dependency.
#
# Pick the GPU from a fresh `myfree`. The default assumes an a6000 is free on `general`.

set -euo pipefail
REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO"

STAGE=""; DRYRUN=0
GPU_PARTITION="general"; GPU_GRES="gpu:a6000:1"; GPU_NODELIST=""
CPU_PARTITION="cpu"
GEN_TIME="08:00:00"; ROSETTA_TIME="08:00:00"; REPORT_TIME="01:00:00"
# The smoke asks for much less wall time than the sweep on purpose: a6000s here are often
# backfill-reserved, and a short request schedules in a gap a long one cannot fit.
SMOKE_TIME="00:30:00"
# Host memory. The sbatch files ask 64G, which is right for a full sweep shard but too
# much for a smoke: a6000 nodes here are often the free GPU on a box whose RAM is mostly
# taken, and an over-provisioned request simply does not schedule.
GPU_MEM=""
SHARDS=1
SMOKE=0
declare -a EXTRA_ENV=()

usage() { sed -n '2,24p' "$0"; exit "${1:-0}"; }

while [[ $# -gt 0 ]]; do
  case "$1" in
    --submit)        STAGE="$2";        shift 2 ;;
    --gpu-partition) GPU_PARTITION="$2"; shift 2 ;;
    --gpu-gres)      GPU_GRES="$2";     shift 2 ;;
    --gpu-nodelist)  GPU_NODELIST="$2"; shift 2 ;;
    --cpu-partition) CPU_PARTITION="$2"; shift 2 ;;
    --gen-time)      GEN_TIME="$2";     shift 2 ;;
    --rosetta-time)  ROSETTA_TIME="$2"; shift 2 ;;
    --shards)        SHARDS="$2";       shift 2 ;;
    # Any VAR=value goes into the env file, so every knob in _flowedit_preamble.sh is
    # settable without editing a script.
    --set)           EXTRA_ENV+=("$2"); shift 2 ;;
    --smoke)         SMOKE=1;           shift ;;
    --smoke-time)    SMOKE_TIME="$2";   shift 2 ;;
    --mem)           GPU_MEM="$2";      shift 2 ;;
    --dry-run)       DRYRUN=1;          shift ;;
    -h|--help)       usage 0 ;;
    *) echo "unknown arg: $1" >&2; usage 1 >&2 ;;
  esac
done
[[ -n "$STAGE" ]] || { echo "FATAL: --submit <stage> is required" >&2; usage 1 >&2; }
# The `smoke` stage IS a smoke run; requiring --smoke as well would let it silently submit
# a full-size sweep under a name that says otherwise.
[[ "$STAGE" == "smoke" ]] && SMOKE=1

mkdir -p env_files slurm_logs
STAMP="$(date +%Y%m%d_%H%M%S)"
ENV_FILE="${REPO}/env_files/flowedit_${STAMP}.env"

# The env file is SOURCED by the job, so every value must be quoted. A bare
# `SEEDS=0 1` is not an assignment of a two-word value -- bash reads it as "run the
# command `1` with SEEDS=0 in its environment" and the job dies with `1: command not
# found`. Measured: job 67817. Several of this pipeline's knobs are space-separated
# lists (SEEDS, T_LAT, CYC_TYPES, EXTRA_ARGS), so this is the normal case, not an edge
# one. `emit` splits on the FIRST `=` and single-quotes the value, escaping any embedded
# single quote, so a value may contain spaces, quotes or globs safely.
emit() {
  local kv="$1" name val
  name="${kv%%=*}"
  val="${kv#*=}"
  if [[ "$name" == "$kv" ]]; then  # no `=` at all: pass through (e.g. a comment)
    printf '%s\n' "$kv"
    return
  fi
  printf "%s='%s'\n" "$name" "${val//\'/\'\\\'\'}"
}

# Emitting a default RUN_TAG that a later --set then overrides works (the last assignment
# wins on source) but makes the file read as if the run had two names.
has_set() { [[ " ${EXTRA_ENV[*]+${EXTRA_ENV[*]}} " == *" $1="* ]]; }

{
  echo "# generated by submit_flowedit.sh at ${STAMP}"
  emit "REPO=${REPO}"
  has_set RUN_TAG || emit "RUN_TAG=${RUN_TAG:-flowedit_${STAMP}}"
  emit "SHARD_COUNT=${SHARDS}"
  if [[ $SMOKE -eq 1 ]]; then
    emit "LIMIT=3"; emit "SEEDS=0 1"; emit "T_LAT=0.6"
    emit "CYC_TYPES=mainchain disulfide isopeptide"
    emit "NSTEPS=100"; emit "WRITE_IF=all"
  fi
  for kv in "${EXTRA_ENV[@]+"${EXTRA_ENV[@]}"}"; do emit "$kv"; done
} > "$ENV_FILE"
echo "env file: $ENV_FILE"
sed 's/^/  /' "$ENV_FILE"

NODELIST_ARG=(); [[ -n "$GPU_NODELIST" ]] && NODELIST_ARG=(--nodelist="$GPU_NODELIST")
MEM_ARG=();      [[ -n "$GPU_MEM" ]]      && MEM_ARG=(--mem="$GPU_MEM")

submit() {  # submit <description> <sbatch args...>
  local desc="$1"; shift
  if [[ $DRYRUN -eq 1 ]]; then
    { printf 'DRY-RUN %-16s sbatch' "$desc"; printf ' %q' "$@"; printf '\n'; } >&2
    echo "999999"; return
  fi
  local out; out="$(sbatch "$@")"
  echo "$desc: $out" >&2
  awk '{print $NF}' <<<"$out"
}

ARRAY_ARG=()
[[ "$SHARDS" -gt 1 ]] && ARRAY_ARG=(--array="0-$((SHARDS - 1))")

GEN_JIDS=()

if [[ "$STAGE" == "smoke" ]]; then
  # One real end-to-end run, both arms, everything scored. Deliberately not a separate
  # readiness project: it is the same code path the sweep uses, just small.
  for m in flowedit sdedit; do
    submit "smoke:$m" \
      --partition="$GPU_PARTITION" --gres="$GPU_GRES" --time="$SMOKE_TIME" \
      "${NODELIST_ARG[@]}" "${MEM_ARG[@]}" \
      scripts/flowedit_gpu.sbatch "$ENV_FILE" "METHOD=$m" >/dev/null
  done
fi

if [[ "$STAGE" == "gen" ]]; then
  submit "gen:${METHOD:-flowedit}" \
    --partition="$GPU_PARTITION" --gres="$GPU_GRES" --time="$GEN_TIME" \
    "${ARRAY_ARG[@]}" "${NODELIST_ARG[@]}" "${MEM_ARG[@]}" \
    scripts/flowedit_gpu.sbatch "$ENV_FILE" "METHOD=${METHOD:-flowedit}" >/dev/null
fi

if [[ "$STAGE" == "paired" || "$STAGE" == "all" ]]; then
  # Siblings, not a chain: they are the comparison, so they queue concurrently and neither
  # waits on the other. Submitting one without the other produces an uninterpretable result.
  for m in flowedit sdedit; do
    GEN_JIDS+=("$(submit "gen:$m" \
      --partition="$GPU_PARTITION" --gres="$GPU_GRES" --time="$GEN_TIME" \
      "${ARRAY_ARG[@]}" "${NODELIST_ARG[@]}" "${MEM_ARG[@]}" \
      scripts/flowedit_gpu.sbatch "$ENV_FILE" "METHOD=$m")")
  done
fi

if [[ "$STAGE" == "rosetta" || "$STAGE" == "all" ]]; then
  DEP=()
  if [[ ${#GEN_JIDS[@]} -gt 0 ]]; then
    # afterany, not afterok: a shard that dies late still leaves scorable rows, and the
    # Rosetta stage gates on its own input instead of on the upstream exit code.
    DEP=(--dependency=afterany:"$(IFS=:; echo "${GEN_JIDS[*]}")")
  fi
  submit "rosetta" \
    --partition="$CPU_PARTITION" --time="$ROSETTA_TIME" \
    "${DEP[@]}" \
    scripts/flowedit_rosetta.sbatch "$ENV_FILE" >/dev/null
fi

if [[ "$STAGE" == "report" || "$STAGE" == "all" ]]; then
  submit "report" \
    --partition="$CPU_PARTITION" --time="$REPORT_TIME" \
    scripts/flowedit_report.sbatch "$ENV_FILE" >/dev/null
fi

case "$STAGE" in
  smoke|gen|paired|rosetta|report|all) ;;
  *) echo "FATAL: unknown stage '$STAGE'" >&2; usage 1 >&2 ;;
esac
echo "submitted stage: $STAGE"
